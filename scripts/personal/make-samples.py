def report(path):
    rows = "\n".join(f"<tr><td>{n}</td><td class=v>{v}</td><td>{u}</td><td>{r}</td><td class=f>{f}</td></tr>" for n, v, u, r, f in LABS)
    path.write_text(f"""<!doctype html><meta charset=utf-8><title>Laboratory report</title>
<style>body{{font:12px/1.45 Georgia,serif;margin:40px;color:#222}}h1{{font:600 18px Arial;margin:0}}.hd{{display:flex;justify-content:space-between;border-bottom:2px solid #333;padding-bottom:8px;margin-bottom:14px}}
table{{width:100%;border-collapse:collapse}}th,td{{text-align:left;padding:4px 6px;border-bottom:1px solid #ddd}}th{{font:600 11px Arial;background:#f2f2f2}}.v{{font-weight:600}}.f{{color:#b00;font-weight:700}}small{{color:#666}}</style>
<div class=hd><div><h1>Sample Community Laboratory</h1><small>Not a real laboratory. Sample data for testing.</small></div>
<div>Patient: <b>Sam Sample</b><br>DOB: 14/02/1971 · Sex: M<br>Collected: 14/03/2017 07:40 (fasting)<br>Reported: 15/03/2017</div></div>
<table><tr><th>Test</th><th>Result</th><th>Units</th><th>Reference range</th><th>Flag</th></tr>
{rows}</table><p><small>Comment: fasting sample. Results outside the reference range are flagged H (high) or L (low).</small></p>""")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    d, meals = frame("example_data_hall"), frame("example_meals_hall")
    sam = subject(d, "2133-018")
    dexcom(sam, OUT / "sam-dexcom.csv")
    libre(subject(d, "2133-039"), OUT / "hall-2133-039-libre.csv")
    names = {"CF": "Cornflakes and milk", "PB": "Peanut butter sandwich", "Bar": "Protein bar"}
    logged = [{"subject": m.id, "meal": names[m.meal.split()[0]], "time": f"{local(m.mealtime):%Y-%m-%dT%H:%M}"} for m in meals.itertuples()]
    (OUT / "hall-meals.json").write_text(json.dumps(logged, indent=1) + "\n")
    first = sam[0][0].replace(hour=0, minute=0, second=0, microsecond=0)
    apple_health([first + timedelta(days=i) for i in range((sam[-1][0] - first).days + 1)], OUT / "sam-apple-health.xml")
    report(OUT / "sam-blood-test.html")
    print("wrote", *sorted(p.name for p in OUT.iterdir()))


if __name__ == "__main__":
    main()
