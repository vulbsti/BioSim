"""Builds the sample personal data in public/samples/personal/.

Real CGM data: Hall et al. (2018), "Glucotypes reveal new patterns of glucose dysregulation", PLOS
Biology 16(7): e2005143, doi:10.1371/journal.pbio.2005143 (CC BY 4.0), as packaged in the iglu R
package (github.com/irinagain/iglu, data/example_data_hall.rda and example_meals_hall.rda). Dexcom G4
readings every 5 minutes, with the times of three standardised breakfasts (cornflakes and milk,
peanut butter sandwich, protein bar).

Everything else (band data, blood tests) is made up for a sample person, "Sam", who borrows the CGM of
Hall subject 2133-018 (diabetic per the study). Run: python3 scripts/personal/make-samples.py
Needs: pip install rdata
"""
import json, math, random, sys, urllib.request
from datetime import datetime, timedelta, timezone
from pathlib import Path
from zoneinfo import ZoneInfo
import rdata

OUT = Path(__file__).resolve().parents[2] / "public/samples/personal"
CACHE = Path(__file__).resolve().parents[2] / "work/samples"
IGLU = "https://raw.githubusercontent.com/irinagain/iglu/master/data/"
# The study ran at Stanford; times are stored as UTC.
LOCAL = ZoneInfo("America/Los_Angeles")
random.seed(2017)


def frame(name):
    CACHE.mkdir(parents=True, exist_ok=True)
    path = CACHE / f"{name}.rda"
    if not path.exists():
        urllib.request.urlretrieve(IGLU + f"{name}.rda", path)
    return rdata.read_rda(path)[name]


def local(epoch):
    return datetime.fromtimestamp(float(epoch), timezone.utc).astimezone(LOCAL).replace(tzinfo=None)


def dexcom(rows, path):
    out = ["Index,Timestamp (YYYY-MM-DDThh:mm:ss),Event Type,Event Subtype,Patient Info,Device Info,Source Device ID,Glucose Value (mg/dL),Insulin Value (u),Carb Value (grams),Duration (hh:mm:ss),Glucose Rate of Change (mg/dL/min),Transmitter Time (Long Integer),Transmitter ID",
           "1,,FirstName,,Sam,,,,,,,,,", "2,,LastName,,Sample,,,,,,,,,", "3,,Device,,,G4,G4 Receiver,,,,,,,"]
    for i, (t, g) in enumerate(rows, 4):
        out.append(f"{i},{t:%Y-%m-%dT%H:%M:%S},EGV,,,,G4 Receiver,{round(g)},,,,,,")
    path.write_text("\n".join(out) + "\n")


def libre(rows, path):
    head = "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mmol/L,Scan Glucose mmol/L,Non-numeric Rapid-Acting Insulin,Rapid-Acting Insulin (units),Non-numeric Food,Carbohydrates (grams),Carbohydrates (servings),Non-numeric Long-Acting Insulin,Long-Acting Insulin Value (units),Notes,Strip Glucose mmol/L,Ketone mmol/L,Meal Insulin (units),Correction Insulin (units),User Change Insulin (units)"
    out = ["Glucose Data,Generated on,01-07-2017 09:00 UTC,Generated by,Sample Person", head]
    # Libre keeps one automatic reading every 15 minutes.
    for t, g in rows[::3]:
        out.append(f"FreeStyle Libre,SAMPLE01,{t:%d-%m-%Y %H:%M},0,{g / 18.016:.1f}" + "," * 14)
    path.write_text("\n".join(out) + "\n")


def subject(d, sid):
    s = d[d.id == sid].sort_values("time")
    return [(local(t), float(g)) for t, g in zip(s.time, s.gl)]


def apple_health(days, path):
    """A week of Apple Watch records for Sam over the CGM days: heart rate, HRV, steps, sleep, two walks."""
    recs = []
    fmt = lambda t: f"{t:%Y-%m-%d %H:%M:%S} -0700"
    src = 'sourceName="Sam’s Apple Watch" sourceVersion="10.1"'
    def q(kind, start, end, value, unit):
        recs.append(f' <Record type="HKQuantityTypeIdentifier{kind}" {src} unit="{unit}" creationDate="{fmt(end)}" startDate="{fmt(start)}" endDate="{fmt(end)}" value="{value}"/>')
    for day in days:
        bed = day.replace(hour=22, minute=50) + timedelta(minutes=random.randint(-30, 40))
        wake = day.replace(hour=6, minute=40) + timedelta(days=1, minutes=random.randint(-20, 30))
        # Stages: cycles of light, deep, light, REM through the night, with one short waking.
        t, stages = bed + timedelta(minutes=12), []
        while t < wake:
            for stage, mins in (("AsleepCore", 35), ("AsleepDeep", 30 if t < bed + timedelta(hours=4) else 10), ("AsleepCore", 20), ("AsleepREM", 20)):
                end = min(wake, t + timedelta(minutes=mins + random.randint(-5, 5)))
                if end > t: stages.append((stage, t, end))
                t = end
        stages.insert(len(stages) // 2, ("Awake", stages[len(stages) // 2][1], stages[len(stages) // 2][1] + timedelta(minutes=6)))
        recs.append(f' <Record type="HKCategoryTypeIdentifierSleepAnalysis" {src} creationDate="{fmt(wake)}" startDate="{fmt(bed)}" endDate="{fmt(wake)}" value="HKCategoryValueSleepAnalysisInBed"/>')
        for stage, a, b in stages:
            recs.append(f' <Record type="HKCategoryTypeIdentifierSleepAnalysis" {src} creationDate="{fmt(b)}" startDate="{fmt(a)}" endDate="{fmt(b)}" value="HKCategoryValueSleepAnalysis{stage}"/>')
        walk = day.replace(hour=12, minute=30) + timedelta(minutes=random.randint(0, 50))
        for k in range(0, 24 * 60, 5):
            t = day + timedelta(minutes=k)
            asleep = t < day.replace(hour=6, minute=30) or t >= bed
            walking = walk <= t < walk + timedelta(minutes=25)
            hr = (61 if asleep else 78) + random.gauss(0, 3) + (40 if walking else 0)
            q("HeartRate", t, t, round(hr), "count/min")
            if not asleep:
                steps = random.randint(110, 125) * 5 if walking else (random.choice([0, 0, 0, 20, 60, 140]))
                if steps: q("StepCount", t, t + timedelta(minutes=5), steps, "count")
        for h in (1, 3, 5):
            q("HeartRateVariabilitySDNN", day.replace(hour=h) + timedelta(days=1), day.replace(hour=h, minute=1) + timedelta(days=1), round(random.gauss(31, 4), 1), "ms")
        q("RestingHeartRate", day.replace(hour=23), day.replace(hour=23), random.randint(63, 67), "count/min")
        q("OxygenSaturation", day.replace(hour=3) + timedelta(days=1), day.replace(hour=3) + timedelta(days=1), round(random.uniform(0.91, 0.95), 2), "%")
        q("RespiratoryRate", day.replace(hour=3) + timedelta(days=1), day.replace(hour=3) + timedelta(days=1), round(random.uniform(15, 17), 1), "count/min")
        recs.append(f' <Workout workoutActivityType="HKWorkoutActivityTypeWalking" duration="25" durationUnit="min" {src} creationDate="{fmt(walk + timedelta(minutes=25))}" startDate="{fmt(walk)}" endDate="{fmt(walk + timedelta(minutes=25))}"/>')
    path.write_text('<?xml version="1.0" encoding="UTF-8"?>\n<HealthData locale="en_US">\n <ExportDate value="2017-03-21 09:00:00 -0700"/>\n <Me HKCharacteristicTypeIdentifierBiologicalSex="HKBiologicalSexMale"/>\n' + "\n".join(recs) + "\n</HealthData>\n")


